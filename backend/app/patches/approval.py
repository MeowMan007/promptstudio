"""
TSK-054: Approval tiers + single-use tokens.

Single-use approval tokens gate high-risk patch operations (tier=2).
A token must be generated by a trusted authority, used exactly once,
and expire after a configurable TTL.

Provides:
  - ApprovalToken: token record
  - TokenStore: in-memory store (real impl uses Redis or DB)
  - generate_approval_token(store, ttl_seconds): → token string
  - consume_token(store, token): → ApprovalToken or raises
  - is_token_valid(store, token): → bool (non-consuming check)
"""
from __future__ import annotations

import secrets
import time
from dataclasses import dataclass, field
from typing import Any, Callable


# ---------------------------------------------------------------------------
# Token record
# ---------------------------------------------------------------------------

@dataclass
class ApprovalToken:
    token: str
    issued_at: float            # monotonic timestamp
    ttl_seconds: float
    consumed: bool = False
    consumed_at: float | None = None
    issued_by: str = "system"   # who issued the token
    purpose: str = "patch_approval"

    def is_expired(self, now: float | None = None) -> bool:
        t = now if now is not None else time.monotonic()
        return (t - self.issued_at) >= self.ttl_seconds

    def is_valid(self, now: float | None = None) -> bool:
        return not self.consumed and not self.is_expired(now)


# ---------------------------------------------------------------------------
# Errors
# ---------------------------------------------------------------------------

class TokenNotFoundError(Exception):
    def __init__(self, token: str) -> None:
        super().__init__(f"Approval token not found: {token!r}")
        self.token = token


class TokenExpiredError(Exception):
    def __init__(self, token: str, expired_ago: float) -> None:
        super().__init__(f"Approval token {token!r} expired {expired_ago:.1f}s ago")
        self.token = token
        self.expired_ago = expired_ago


class TokenAlreadyConsumedError(Exception):
    def __init__(self, token: str) -> None:
        super().__init__(f"Approval token {token!r} has already been consumed")
        self.token = token


# ---------------------------------------------------------------------------
# Token store
# ---------------------------------------------------------------------------

@dataclass
class TokenStore:
    """
    In-memory single-use approval token store.
    Inject _clock for deterministic testing.
    """
    _tokens: dict[str, ApprovalToken] = field(default_factory=dict)
    _clock: Callable[[], float] | None = None

    def _now(self) -> float:
        return self._clock() if self._clock is not None else time.monotonic()

    def _generate_raw(self) -> str:
        return secrets.token_urlsafe(32)

    def issue(
        self,
        *,
        ttl_seconds: float = 300.0,
        issued_by: str = "system",
        purpose: str = "patch_approval",
    ) -> str:
        """
        Generate and store a new approval token.
        Returns the raw token string (must be passed to the client).
        """
        raw = self._generate_raw()
        record = ApprovalToken(
            token=raw,
            issued_at=self._now(),
            ttl_seconds=ttl_seconds,
            issued_by=issued_by,
            purpose=purpose,
        )
        self._tokens[raw] = record
        return raw

    def consume(self, token: str) -> ApprovalToken:
        """
        Consume a token (single-use).
        Raises TokenNotFoundError, TokenExpiredError, or TokenAlreadyConsumedError.
        """
        now = self._now()
        record = self._tokens.get(token)
        if record is None:
            raise TokenNotFoundError(token)
        if record.consumed:
            raise TokenAlreadyConsumedError(token)
        if record.is_expired(now):
            expired_ago = (now - record.issued_at) - record.ttl_seconds
            raise TokenExpiredError(token, expired_ago)
        record.consumed = True
        record.consumed_at = now
        return record

    def is_valid(self, token: str) -> bool:
        """Non-consuming validity check (for pre-flight)."""
        now = self._now()
        record = self._tokens.get(token)
        if record is None:
            return False
        return record.is_valid(now)

    def valid_tokens(self) -> set[str]:
        """Return set of currently valid (unconsumed, unexpired) token strings."""
        now = self._now()
        return {t for t, r in self._tokens.items() if r.is_valid(now)}

    def purge_expired(self) -> int:
        """Remove all expired tokens. Returns count removed."""
        now = self._now()
        to_remove = [t for t, r in self._tokens.items() if r.is_expired(now)]
        for t in to_remove:
            del self._tokens[t]
        return len(to_remove)
