"""TSK-094: design.md + ADR (MADR) generator.

Implements spec section 24.2:
  - generate_design_md(): embeds diagrams (Mermaid), references decisions
  - generate_adr(): MADR-format Architecture Decision Records
"""
from __future__ import annotations

import hashlib
from dataclasses import dataclass, field
from enum import Enum
from typing import Any


# ---------------------------------------------------------------------------
# Data models
# ---------------------------------------------------------------------------

class ADRStatus(str, Enum):
    PROPOSED = "proposed"
    ACCEPTED = "accepted"
    DEPRECATED = "deprecated"
    SUPERSEDED = "superseded"


@dataclass
class Alternative:
    title: str
    pros: list[str] = field(default_factory=list)
    cons: list[str] = field(default_factory=list)


@dataclass
class DecisionArtifact:
    """A project design decision (maps to an ADR)."""
    adr_id: str             # e.g. "ADR-001"
    title: str
    status: ADRStatus = ADRStatus.PROPOSED
    context: str = ""       # why this decision was needed
    decision: str = ""      # what was decided
    consequences: str = ""  # positive and negative outcomes
    alternatives: list[Alternative] = field(default_factory=list)
    superseded_by: str = "" # e.g. "ADR-005"
    tags: list[str] = field(default_factory=list)


@dataclass
class DiagramBlock:
    """An embedded Mermaid diagram."""
    caption: str
    mermaid_source: str


@dataclass
class DesignSection:
    """A section in the design document."""
    title: str
    content: str
    diagrams: list[DiagramBlock] = field(default_factory=list)
    linked_adrs: list[str] = field(default_factory=list)   # ADR IDs


# ---------------------------------------------------------------------------
# MADR ADR generator
# ---------------------------------------------------------------------------

_MADR_TEMPLATE = """\
# {adr_id}: {title}

**Status:** {status}  
**Tags:** {tags}
{superseded_line}
## Context and Problem Statement

{context}

## Decision Drivers

*(extracted from context above)*

## Considered Options

{options_section}

## Decision Outcome

**Chosen option:** {chosen}

{consequences}

## Pros and Cons of the Options

{pros_cons}
"""


def generate_adr(decision: DecisionArtifact) -> str:
    """Generate a MADR-format ADR markdown string."""
    tags_str = ", ".join(decision.tags) if decision.tags else "*(none)*"
    superseded_line = (
        f"**Superseded by:** {decision.superseded_by}  \n"
        if decision.superseded_by else ""
    )

    # Options list (alternatives + chosen)
    option_names = [alt.title for alt in decision.alternatives]
    if decision.decision and decision.decision not in option_names:
        option_names.insert(0, decision.decision)
    options_section = "\n".join(f"- {o}" for o in option_names) if option_names else "*(none listed)*"

    # Pros/cons section
    pros_cons_parts: list[str] = []
    for alt in decision.alternatives:
        pc = f"### {alt.title}\n\n"
        if alt.pros:
            pc += "**Pros:**\n" + "\n".join(f"- ✅ {p}" for p in alt.pros) + "\n\n"
        if alt.cons:
            pc += "**Cons:**\n" + "\n".join(f"- ❌ {c}" for c in alt.cons) + "\n"
        pros_cons_parts.append(pc)
    pros_cons = "\n".join(pros_cons_parts) if pros_cons_parts else "*(no alternatives documented)*"

    body = _MADR_TEMPLATE.format(
        adr_id=decision.adr_id,
        title=decision.title,
        status=decision.status.value.upper(),
        tags=tags_str,
        superseded_line=superseded_line,
        context=decision.context or "*(not specified)*",
        options_section=options_section,
        chosen=decision.decision or "*(not recorded)*",
        consequences=decision.consequences or "*(not documented)*",
        pros_cons=pros_cons,
    )

    digest = hashlib.sha256(body.encode()).hexdigest()[:16]
    return body + f"\n---\n*Deterministic checksum: `{digest}`*\n"


# ---------------------------------------------------------------------------
# design.md generator
# ---------------------------------------------------------------------------

def generate_design_md(
    sections: list[DesignSection],
    decisions: list[DecisionArtifact] | None = None,
    project_name: str = "",
) -> str:
    """Generate a design.md that embeds Mermaid diagrams and links ADRs.

    Spec 24.2 requirements:
      - Diagrams embedded (fenced ``` mermaid blocks)
      - Decisions linked with their alternatives
    """
    decisions = decisions or []
    adr_index = {d.adr_id: d for d in decisions}

    parts: list[str] = []
    title = f"# Design — {project_name}" if project_name else "# Design"
    parts.append(title + "\n")
    parts.append(
        "> Generated by Prompt Studio. Mermaid diagrams are embedded inline.\n"
        "> Architecture Decision Records (ADRs) follow MADR format.\n"
    )

    # Table of contents
    toc = ["## Table of Contents\n"]
    for i, sec in enumerate(sections, 1):
        slug = sec.title.lower().replace(" ", "-").replace("/", "")
        toc.append(f"{i}. [{sec.title}](#{slug})")
    if decisions:
        toc.append(f"{len(sections)+1}. [Architecture Decisions](#architecture-decisions)")
    parts.append("\n".join(toc) + "\n")

    # Sections
    for sec in sections:
        parts.append(f"\n## {sec.title}\n")
        parts.append(sec.content + "\n")

        # Embed diagrams
        for diagram in sec.diagrams:
            parts.append(f"\n**{diagram.caption}**\n")
            parts.append(f"\n```mermaid\n{diagram.mermaid_source.strip()}\n```\n")

        # Link ADRs
        if sec.linked_adrs:
            refs = []
            for adr_id in sec.linked_adrs:
                if adr_id in adr_index:
                    adr = adr_index[adr_id]
                    refs.append(
                        f"- [{adr_id}: {adr.title}](./decisions/{adr_id}.md)"
                        f" (**{adr.status.value}**)"
                    )
                else:
                    refs.append(f"- {adr_id}")
            parts.append("\n**Related Decisions:**\n\n" + "\n".join(refs) + "\n")

    # ADR index
    if decisions:
        parts.append("\n## Architecture Decisions\n")
        parts.append("| ID | Title | Status | Tags |\n|---|---|---|---|\n")
        for d in decisions:
            tags = ", ".join(d.tags) if d.tags else "—"
            parts.append(f"| [{d.adr_id}](./decisions/{d.adr_id}.md) | {d.title} | {d.status.value} | {tags} |\n")

    body = "\n".join(parts)
    digest = hashlib.sha256(body.encode()).hexdigest()[:16]
    return body + f"\n---\n\n*Deterministic checksum: `{digest}`*\n"
