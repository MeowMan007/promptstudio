"""TSK-095: tasks.md with dependency waves + speckit/kiro profiles.

Implements spec sections 24.3, 24.4:
  - Topological sort of tasks by depends_on → dependency waves
  - Speckit profile (flat task list with metadata)
  - Kiro profile (.kiro/specs/*.md task specs)
"""
from __future__ import annotations

import hashlib
from collections import defaultdict, deque
from dataclasses import dataclass, field
from enum import Enum
from typing import Any


# ---------------------------------------------------------------------------
# Data models
# ---------------------------------------------------------------------------

class TaskStatus(str, Enum):
    TODO = "todo"
    IN_PROGRESS = "in_progress"
    DONE = "done"
    BLOCKED = "blocked"


@dataclass
class Task:
    task_id: str
    title: str
    status: TaskStatus = TaskStatus.TODO
    depends_on: list[str] = field(default_factory=list)
    description: str = ""
    acceptance: str = ""
    priority: str = "P1"
    epic: str = ""
    estimate_hours: float = 0.0
    tags: list[str] = field(default_factory=list)


# ---------------------------------------------------------------------------
# Topological sort → waves
# ---------------------------------------------------------------------------

class CyclicDependencyError(ValueError):
    pass


def compute_waves(tasks: list[Task]) -> list[list[Task]]:
    """Return tasks grouped into dependency waves via Kahn's algorithm.

    Wave 0 = tasks with no dependencies.
    Wave N = tasks whose all dependencies are in waves 0..N-1.

    Raises CyclicDependencyError if a cycle is detected.
    """
    task_map = {t.task_id: t for t in tasks}
    in_degree: dict[str, int] = {t.task_id: 0 for t in tasks}
    children: dict[str, list[str]] = defaultdict(list)

    for task in tasks:
        for dep in task.depends_on:
            if dep in task_map:  # skip unknown deps
                children[dep].append(task.task_id)
                in_degree[task.task_id] += 1

    queue: deque[str] = deque(
        tid for tid, deg in in_degree.items() if deg == 0
    )
    waves: list[list[Task]] = []

    while queue:
        wave_size = len(queue)
        current_wave: list[Task] = []
        for _ in range(wave_size):
            tid = queue.popleft()
            current_wave.append(task_map[tid])
            for child in children[tid]:
                in_degree[child] -= 1
                if in_degree[child] == 0:
                    queue.append(child)
        if current_wave:
            waves.append(sorted(current_wave, key=lambda t: t.task_id))

    total_scheduled = sum(len(w) for w in waves)
    if total_scheduled != len(tasks):
        remaining = {
            tid for tid, deg in in_degree.items() if deg > 0
        }
        raise CyclicDependencyError(
            f"Cycle detected among tasks: {sorted(remaining)}"
        )

    return waves


# ---------------------------------------------------------------------------
# tasks.md generator
# ---------------------------------------------------------------------------

def generate_tasks_md(tasks: list[Task], project_name: str = "") -> str:
    """Generate a tasks.md with wave-ordered task table."""
    waves = compute_waves(tasks)

    title = f"# Tasks — {project_name}" if project_name else "# Tasks"
    parts = [
        title,
        "\n> Generated by Prompt Studio. Tasks are grouped into dependency waves.",
        "> Tasks in the same wave have no inter-dependencies and can run in parallel.\n",
    ]

    for wave_idx, wave in enumerate(waves):
        parts.append(f"\n## Wave {wave_idx}\n")
        parts.append("| Task ID | Title | Priority | Status | Depends On | Estimate (h) |")
        parts.append("|---------|-------|----------|--------|-----------|-------------|")
        for t in wave:
            deps = ", ".join(t.depends_on) if t.depends_on else "—"
            est = f"{t.estimate_hours:.1f}" if t.estimate_hours else "—"
            parts.append(
                f"| {t.task_id} | {t.title} | {t.priority} | "
                f"{t.status.value} | {deps} | {est} |"
            )

    # Summary stats
    done_count = sum(1 for t in tasks if t.status == TaskStatus.DONE)
    parts.append(f"\n---\n\n**Summary:** {done_count}/{len(tasks)} tasks done, {len(waves)} wave(s).\n")

    body = "\n".join(parts)
    digest = hashlib.sha256(body.encode()).hexdigest()[:16]
    return body + f"\n*Deterministic checksum: `{digest}`*\n"


# ---------------------------------------------------------------------------
# Speckit profile
# ---------------------------------------------------------------------------

def generate_speckit_profile(tasks: list[Task], project_name: str = "") -> str:
    """Generate a speckit-compatible YAML task list."""
    lines = [
        f"# Speckit profile — {project_name}",
        "# Generated by Prompt Studio",
        "tasks:",
    ]
    for t in sorted(tasks, key=lambda x: x.task_id):
        lines.append(f"  - id: {t.task_id}")
        lines.append(f"    title: {t.title!r}")
        lines.append(f"    status: {t.status.value}")
        lines.append(f"    priority: {t.priority}")
        if t.depends_on:
            deps = ", ".join(t.depends_on)
            lines.append(f"    depends_on: [{deps}]")
        if t.acceptance:
            lines.append(f"    acceptance: {t.acceptance!r}")
        if t.estimate_hours:
            lines.append(f"    estimate_hours: {t.estimate_hours}")
    return "\n".join(lines) + "\n"


# ---------------------------------------------------------------------------
# Kiro profile (.kiro/specs/*.md files)
# ---------------------------------------------------------------------------

def generate_kiro_specs(tasks: list[Task]) -> dict[str, str]:
    """Generate .kiro/specs/<task_id>.md files for each task.

    Returns dict of path → content.
    """
    result: dict[str, str] = {}
    for t in tasks:
        body = (
            f"# {t.task_id}: {t.title}\n\n"
            f"**Status:** {t.status.value}  \n"
            f"**Priority:** {t.priority}  \n"
            f"**Epic:** {t.epic or '—'}  \n"
        )
        if t.depends_on:
            body += f"**Depends on:** {', '.join(t.depends_on)}  \n"
        body += "\n## Description\n\n"
        body += (t.description or "*(not specified)*") + "\n\n"
        body += "## Acceptance Criteria\n\n"
        body += (t.acceptance or "*(not specified)*") + "\n"
        if t.tags:
            body += f"\n**Tags:** {', '.join(t.tags)}\n"

        digest = hashlib.sha256(body.encode()).hexdigest()[:16]
        body += f"\n---\n*checksum: `{digest}`*\n"
        result[f".kiro/specs/{t.task_id}.md"] = body

    return result
