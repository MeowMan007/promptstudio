"""TSK-093: requirements.md (EARS) + acceptance-criteria + matrix generator.

Implements spec section 24.1 / 25.5:
  - Five EARS patterns: Ubiquitous, Event-driven, Unwanted Behavior,
    State-driven, Optional Feature
  - Acceptance-criteria table per requirement
  - Traceability matrix: Req → Artifact → Test
"""
from __future__ import annotations

import hashlib
from dataclasses import dataclass, field
from enum import Enum
from typing import Any


class EARSPattern(str, Enum):
    """The five EARS requirement pattern types."""
    UBIQUITOUS = "ubiquitous"           # The <system> shall …
    EVENT_DRIVEN = "event_driven"       # When <trigger>, the <system> shall …
    UNWANTED_BEHAVIOR = "unwanted"      # If <condition>, the <system> shall …
    STATE_DRIVEN = "state_driven"       # While <state>, the <system> shall …
    OPTIONAL_FEATURE = "optional"       # Where <feature>, the <system> shall …


_PATTERN_PREFIX: dict[EARSPattern, str] = {
    EARSPattern.UBIQUITOUS: "The system shall",
    EARSPattern.EVENT_DRIVEN: "When {trigger}, the system shall",
    EARSPattern.UNWANTED_BEHAVIOR: "If {condition}, the system shall",
    EARSPattern.STATE_DRIVEN: "While {state}, the system shall",
    EARSPattern.OPTIONAL_FEATURE: "Where {feature} is available, the system shall",
}


@dataclass
class Requirement:
    req_id: str                          # e.g. "REQ-001"
    title: str
    pattern: EARSPattern
    action: str                          # the "shall …" payload
    # Context keyword depends on pattern: trigger / condition / state / feature
    context: str = ""
    priority: str = "Must"               # Must / Should / Could / Won't
    acceptance_criteria: list[str] = field(default_factory=list)
    linked_artifacts: list[str] = field(default_factory=list)
    linked_tests: list[str] = field(default_factory=list)


def _format_ears_statement(req: Requirement) -> str:
    prefix_tpl = _PATTERN_PREFIX[req.pattern]
    if req.pattern == EARSPattern.UBIQUITOUS:
        prefix = prefix_tpl
    elif req.pattern == EARSPattern.EVENT_DRIVEN:
        prefix = prefix_tpl.format(trigger=req.context or "the trigger occurs")
    elif req.pattern == EARSPattern.UNWANTED_BEHAVIOR:
        prefix = prefix_tpl.format(condition=req.context or "an error condition occurs")
    elif req.pattern == EARSPattern.STATE_DRIVEN:
        prefix = prefix_tpl.format(state=req.context or "the system is in a valid state")
    else:  # OPTIONAL_FEATURE
        prefix = prefix_tpl.format(feature=req.context or "the optional feature")
    return f"{prefix} {req.action}."


def _acceptance_rows(req: Requirement) -> str:
    if not req.acceptance_criteria:
        return "| *(none defined)* | — |"
    return "\n".join(
        f"| AC-{i+1:02d} | {ac} |"
        for i, ac in enumerate(req.acceptance_criteria)
    )


def _matrix_row(req: Requirement) -> str:
    artifacts = ", ".join(req.linked_artifacts) if req.linked_artifacts else "—"
    tests = ", ".join(req.linked_tests) if req.linked_tests else "—"
    return f"| {req.req_id} | {req.title} | {artifacts} | {tests} |"


def generate_requirements_md(requirements: list[Requirement], project_name: str = "") -> str:
    """Generate a full requirements.md document.

    Covers spec 24.1 and 25.5:
      - EARS-formatted requirements grouped by pattern
      - Acceptance criteria per requirement
      - Traceability matrix: Req → Artifacts → Tests
    """
    sections: list[str] = []

    title = f"# Requirements — {project_name}" if project_name else "# Requirements"
    sections.append(title)
    sections.append(
        "\n> Generated by Prompt Studio. All requirements use EARS notation.\n"
        "> **Patterns:** Ubiquitous · Event-driven · Unwanted Behavior · "
        "State-driven · Optional Feature\n"
    )

    # Group by pattern
    grouped: dict[EARSPattern, list[Requirement]] = {p: [] for p in EARSPattern}
    for req in requirements:
        grouped[req.pattern].append(req)

    pattern_titles = {
        EARSPattern.UBIQUITOUS: "Ubiquitous Requirements",
        EARSPattern.EVENT_DRIVEN: "Event-Driven Requirements",
        EARSPattern.UNWANTED_BEHAVIOR: "Unwanted Behaviour Requirements",
        EARSPattern.STATE_DRIVEN: "State-Driven Requirements",
        EARSPattern.OPTIONAL_FEATURE: "Optional-Feature Requirements",
    }

    for pattern, title_str in pattern_titles.items():
        reqs = grouped[pattern]
        if not reqs:
            continue
        sections.append(f"\n## {title_str}\n")
        for req in reqs:
            statement = _format_ears_statement(req)
            sections.append(f"### {req.req_id} — {req.title}\n")
            sections.append(f"**Priority:** {req.priority}  \n")
            sections.append(f"**Statement:** {statement}\n")
            if req.acceptance_criteria:
                sections.append(
                    "\n**Acceptance Criteria:**\n\n"
                    "| ID | Criterion |\n"
                    "|----|----------|\n"
                    + _acceptance_rows(req)
                    + "\n"
                )

    # Traceability matrix
    sections.append("\n## Traceability Matrix\n")
    sections.append(
        "| Req ID | Title | Linked Artifacts | Linked Tests |\n"
        "|--------|-------|-----------------|-------------|\n"
        + "\n".join(_matrix_row(r) for r in requirements)
        + "\n"
    )

    body = "\n".join(sections)
    digest = hashlib.sha256(body.encode()).hexdigest()[:16]
    return body + f"\n---\n\n*Deterministic checksum: `{digest}`*\n"
