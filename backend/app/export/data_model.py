"""TSK-097: SQL DDL + DBML generators with parity test.

Implements spec section 25.3:
  - generate_sql_ddl(): PostgreSQL DDL from data-entity artifacts
  - generate_dbml(): DBML format from same entities
  - assert_parity(): structural parity test between DDL and DBML
"""
from __future__ import annotations

import hashlib
import re
from dataclasses import dataclass, field
from enum import Enum
from typing import Any


# ---------------------------------------------------------------------------
# Data models
# ---------------------------------------------------------------------------

class ColumnType(str, Enum):
    TEXT = "TEXT"
    INTEGER = "INTEGER"
    BIGINT = "BIGINT"
    BOOLEAN = "BOOLEAN"
    FLOAT = "FLOAT"
    DECIMAL = "DECIMAL"
    UUID = "UUID"
    TIMESTAMP = "TIMESTAMPTZ"
    JSONB = "JSONB"
    BYTEA = "BYTEA"


# DBML equivalents for each ColumnType
_DBML_TYPE: dict[ColumnType, str] = {
    ColumnType.TEXT: "text",
    ColumnType.INTEGER: "integer",
    ColumnType.BIGINT: "bigint",
    ColumnType.BOOLEAN: "boolean",
    ColumnType.FLOAT: "float",
    ColumnType.DECIMAL: "decimal",
    ColumnType.UUID: "uuid",
    ColumnType.TIMESTAMP: "timestamptz",
    ColumnType.JSONB: "jsonb",
    ColumnType.BYTEA: "bytea",
}


@dataclass
class Column:
    name: str
    col_type: ColumnType
    nullable: bool = True
    primary_key: bool = False
    unique: bool = False
    default: str = ""          # SQL literal, e.g. "gen_random_uuid()"
    references: str = ""       # e.g. "users.id"
    description: str = ""


@dataclass
class Index:
    columns: list[str]
    unique: bool = False
    name: str = ""


@dataclass
class DataEntity:
    table_name: str
    columns: list[Column]
    indexes: list[Index] = field(default_factory=list)
    dialect: str = "postgresql"
    description: str = ""


# ---------------------------------------------------------------------------
# SQL DDL generator
# ---------------------------------------------------------------------------

def _ddl_column(col: Column) -> str:
    parts = [f'  "{col.name}"', col.col_type.value]
    if col.primary_key:
        parts.append("PRIMARY KEY")
    if not col.nullable and not col.primary_key:
        parts.append("NOT NULL")
    if col.unique and not col.primary_key:
        parts.append("UNIQUE")
    if col.default:
        parts.append(f"DEFAULT {col.default}")
    if col.references:
        ref_table, ref_col = col.references.rsplit(".", 1)
        parts.append(f'REFERENCES "{ref_table}" ("{ref_col}")')
    return " ".join(parts)


def generate_sql_ddl(entities: list[DataEntity]) -> str:
    """Generate PostgreSQL DDL for a list of data entities.

    Output is deterministic (entities sorted by table_name).
    """
    stmts: list[str] = [
        "-- SQL DDL generated by Prompt Studio",
        "-- dialect: postgresql\n",
    ]

    sorted_entities = sorted(entities, key=lambda e: e.table_name)
    for entity in sorted_entities:
        if entity.description:
            stmts.append(f"-- {entity.description}")
        col_defs = [_ddl_column(c) for c in entity.columns]
        col_block = ",\n".join(col_defs)
        stmts.append(f'CREATE TABLE IF NOT EXISTS "{entity.table_name}" (\n{col_block}\n);\n')

        for idx in entity.indexes:
            unique_kw = "UNIQUE " if idx.unique else ""
            idx_name = idx.name or f"idx_{entity.table_name}_{'_'.join(idx.columns)}"
            cols = ", ".join(f'"{c}"' for c in idx.columns)
            stmts.append(
                f'CREATE {unique_kw}INDEX IF NOT EXISTS "{idx_name}" '
                f'ON "{entity.table_name}" ({cols});\n'
            )

    body = "\n".join(stmts)
    digest = hashlib.sha256(body.encode()).hexdigest()[:16]
    return body + f"\n-- checksum: {digest}\n"


# ---------------------------------------------------------------------------
# DBML generator
# ---------------------------------------------------------------------------

def _dbml_column(col: Column) -> str:
    dbml_type = _DBML_TYPE.get(col.col_type, col.col_type.value.lower())
    attrs: list[str] = []
    if col.primary_key:
        attrs.append("pk")
    if not col.nullable and not col.primary_key:
        attrs.append("not null")
    if col.unique and not col.primary_key:
        attrs.append("unique")
    if col.default:
        attrs.append(f"default: `{col.default}`")
    if col.description:
        attrs.append(f"note: '{col.description}'")
    attr_str = f" [{', '.join(attrs)}]" if attrs else ""
    return f"  {col.name} {dbml_type}{attr_str}"


def generate_dbml(entities: list[DataEntity]) -> str:
    """Generate DBML from a list of data entities.

    Includes table definitions and ref declarations.
    """
    lines: list[str] = [
        "// DBML generated by Prompt Studio",
        "// Use https://dbdiagram.io to visualise\n",
    ]
    refs: list[str] = []

    sorted_entities = sorted(entities, key=lambda e: e.table_name)
    for entity in sorted_entities:
        if entity.description:
            lines.append(f"// {entity.description}")
        lines.append(f"Table {entity.table_name} {{")
        for col in entity.columns:
            lines.append(_dbml_column(col))
            if col.references:
                ref_table, ref_col = col.references.rsplit(".", 1)
                refs.append(
                    f"Ref: {entity.table_name}.{col.name} > {ref_table}.{ref_col}"
                )
        if entity.indexes:
            lines.append("")
            lines.append("  indexes {")
            for idx in entity.indexes:
                cols = ", ".join(idx.columns)
                unique_kw = " [unique]" if idx.unique else ""
                lines.append(f"    ({cols}){unique_kw}")
            lines.append("  }")
        lines.append("}\n")

    if refs:
        lines.append("// Foreign key references")
        lines.extend(refs)

    body = "\n".join(lines)
    digest = hashlib.sha256(body.encode()).hexdigest()[:16]
    return body + f"\n// checksum: {digest}\n"


# ---------------------------------------------------------------------------
# Parity test (spec 25.3: "both describe identical structures")
# ---------------------------------------------------------------------------

class ParityError(AssertionError):
    pass


def _extract_ddl_tables(ddl: str) -> dict[str, set[str]]:
    """Return {table_name: {col_name, ...}} from DDL text."""
    result: dict[str, set[str]] = {}
    table_re = re.compile(r'CREATE TABLE IF NOT EXISTS "(\w+)" \(([^;]+)\)', re.S)
    col_re = re.compile(r'"(\w+)"\s+\w+')
    for m in table_re.finditer(ddl):
        table = m.group(1)
        body = m.group(2)
        cols = {c for c in col_re.findall(body)}
        result[table] = cols
    return result


def _extract_dbml_tables(dbml: str) -> dict[str, set[str]]:
    """Return {table_name: {col_name, ...}} from DBML text."""
    result: dict[str, set[str]] = {}
    table_re = re.compile(r"Table (\w+) \{([^}]+)\}", re.S)
    col_re = re.compile(r"^\s+(\w+)\s+\w+", re.M)
    for m in table_re.finditer(dbml):
        table = m.group(1)
        body = m.group(2)
        cols = {c for c in col_re.findall(body)}
        result[table] = cols
    return result


def assert_ddl_dbml_parity(ddl: str, dbml: str) -> None:
    """Assert that DDL and DBML describe the same tables and columns.

    Raises ParityError with a diff if they diverge.
    """
    ddl_tables = _extract_ddl_tables(ddl)
    dbml_tables = _extract_dbml_tables(dbml)

    errors: list[str] = []

    only_ddl = set(ddl_tables) - set(dbml_tables)
    only_dbml = set(dbml_tables) - set(ddl_tables)
    if only_ddl:
        errors.append(f"Tables in DDL but not DBML: {sorted(only_ddl)}")
    if only_dbml:
        errors.append(f"Tables in DBML but not DDL: {sorted(only_dbml)}")

    for table in set(ddl_tables) & set(dbml_tables):
        ddl_cols = ddl_tables[table]
        dbml_cols = dbml_tables[table]
        only_ddl_cols = ddl_cols - dbml_cols
        only_dbml_cols = dbml_cols - ddl_cols
        if only_ddl_cols:
            errors.append(f"Table {table!r}: columns in DDL not in DBML: {sorted(only_ddl_cols)}")
        if only_dbml_cols:
            errors.append(f"Table {table!r}: columns in DBML not in DDL: {sorted(only_dbml_cols)}")

    if errors:
        raise ParityError("DDL/DBML parity check failed:\n" + "\n".join(f"  • {e}" for e in errors))
